#!/usr/bin/env python3
"""Tests for the generated plugin marketplace manifests.

Usage: python3 -m unittest tests/test_plugin_manifests.py [-v]
Run from the repo root.

Covers the Claude (.claude-plugin/), Cursor (.cursor-plugin/) and Codex
(.agents/plugins/ + .codex-plugin/) manifests generated by scripts/gen_*.py
from scripts/catalog_lib.py's Catalog. The Claude manifest is written by a
parallel generator (scripts/gen_claude.py); until that generator and its
output are merged into this worktree, TestClaudeManifest fails on the
missing file -- that is expected, not a bug in this test.
"""
from __future__ import annotations

import importlib.util
import json
import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = REPO_ROOT / "scripts"
sys.path.insert(0, str(SCRIPTS_DIR))

import catalog_lib  # noqa: E402  (path set up above)

MANIFEST_PATHS = (
    ".claude-plugin/marketplace.json",
    ".cursor-plugin/marketplace.json",
    ".cursor-plugin/plugin.json",
    ".agents/plugins/marketplace.json",
    ".codex-plugin/plugin.json",
)


def _load_module(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _read_json(relpath: str) -> dict:
    path = REPO_ROOT / relpath
    return json.loads(path.read_text(encoding="utf-8"))


def _require_json(test: unittest.TestCase, relpath: str) -> dict:
    path = REPO_ROOT / relpath
    test.assertTrue(path.is_file(), f"missing {relpath}")
    return json.loads(path.read_text(encoding="utf-8"))


def _plugin_names_in(data: dict) -> list[str]:
    """Every marketplace-entry plugin name in a marketplace manifest dict."""
    return [
        plugin["name"]
        for plugin in data.get("plugins", [])
        if isinstance(plugin, dict) and isinstance(plugin.get("name"), str)
    ]


def _skill_names_one_level(dir_path: Path) -> list[str]:
    """Cursor's scan: each listed dir is scanned one level deep for <skill>/SKILL.md."""
    if not dir_path.is_dir():
        return []
    return [
        child.name
        for child in sorted(dir_path.iterdir())
        if child.is_dir() and (child / "SKILL.md").is_file()
    ]


def _skill_names_recursive(root: Path, max_depth: int) -> list[str]:
    """Codex's scan: recurse from the manifest's skills path to depth max_depth."""
    found: list[str] = []

    def walk(current: Path, depth: int) -> None:
        if depth > max_depth or not current.is_dir():
            return
        for child in sorted(current.iterdir()):
            if child.is_dir():
                if (child / "SKILL.md").is_file():
                    found.append(child.name)
                walk(child, depth + 1)

    walk(root, 1)
    return found


class CatalogFixture(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalog = catalog_lib.load_catalog(REPO_ROOT)
        cls.all_skill_names = sorted(s.name for s in cls.catalog.skills)


class TestManifestsGeneral(CatalogFixture):
    def test_each_manifest_parses_as_json(self):
        for relpath in MANIFEST_PATHS:
            path = REPO_ROOT / relpath
            with self.subTest(relpath=relpath):
                self.assertTrue(path.is_file(), f"missing {relpath}")
                json.loads(path.read_text(encoding="utf-8"))

    def test_no_claude_plugin_json(self):
        self.assertFalse(
            (REPO_ROOT / ".claude-plugin" / "plugin.json").exists(),
            ".claude-plugin/plugin.json must not exist (conflicts with strict:false + skills)",
        )

    def test_no_plugin_named_bare_harness(self):
        names: list[str] = []
        for relpath in MANIFEST_PATHS:
            path = REPO_ROOT / relpath
            if not path.is_file():
                continue
            data = json.loads(path.read_text(encoding="utf-8"))
            names.extend(_plugin_names_in(data))
            if relpath.endswith("plugin.json") and isinstance(data.get("name"), str):
                names.append(data["name"])
        self.assertNotIn("harness", names)


class TestClaudeManifest(CatalogFixture):
    """Expected to fail in this worktree: .claude-plugin/marketplace.json is
    written by the parallel Claude-generator stream and is not present here."""

    def test_marketplace_name(self):
        data = _require_json(self, ".claude-plugin/marketplace.json")
        self.assertEqual(data["name"], catalog_lib.MARKETPLACE_NAME)

    def test_plugin_entries_match_categories_in_order(self):
        data = _require_json(self, ".claude-plugin/marketplace.json")
        plugins = data["plugins"]
        self.assertEqual(len(plugins), len(self.catalog.categories))
        seen_names: set[str] = set()
        for plugin, cat in zip(plugins, self.catalog.categories):
            n = len(cat.skills)
            label = catalog_lib.count_label(n)
            with self.subTest(plugin=cat.plugin):
                self.assertEqual(plugin["name"], cat.plugin)
                self.assertEqual(plugin["source"], ".")
                self.assertEqual(plugin["strict"], False)
                self.assertEqual(plugin["skills"], [f"./skills/{cat.dir}"])
                self.assertNotIn("version", plugin)
                self.assertNotIn("mcpServers", plugin)
                self.assertTrue(plugin["description"].startswith(f"{label}: "))
                self.assertFalse(plugin["name"].startswith("claude-"))
                self.assertFalse(plugin["name"].startswith("anthropic-"))
                self.assertNotIn(plugin["name"], seen_names)
                seen_names.add(plugin["name"])

    def test_each_category_dir_has_exactly_n_skills_one_level_deep(self):
        data = _require_json(self, ".claude-plugin/marketplace.json")
        for plugin, cat in zip(data["plugins"], self.catalog.categories):
            with self.subTest(dir=cat.dir):
                found = _skill_names_one_level(REPO_ROOT / "skills" / cat.dir)
                self.assertEqual(sorted(found), sorted(s.name for s in cat.skills))
                self.assertEqual(plugin["skills"], [f"./skills/{cat.dir}"])


class TestCursorManifest(CatalogFixture):
    def test_marketplace_has_exactly_one_entry_naming_the_umbrella(self):
        marketplace = _read_json(".cursor-plugin/marketplace.json")
        plugin = _read_json(".cursor-plugin/plugin.json")
        self.assertEqual(len(marketplace["plugins"]), 1)
        entry = marketplace["plugins"][0]
        self.assertEqual(entry["name"], catalog_lib.UMBRELLA_NAME)
        self.assertEqual(plugin["name"], catalog_lib.UMBRELLA_NAME)

    def test_source_resolves_to_repo_root(self):
        marketplace = _read_json(".cursor-plugin/marketplace.json")
        entry = marketplace["plugins"][0]
        # Cursor's source resolver treats a bare "." (or "./") as the
        # marketplace root itself -- see citation list in the report.
        self.assertEqual(entry["source"], ".")

    def test_plugin_version_matches_catalog(self):
        plugin = _read_json(".cursor-plugin/plugin.json")
        self.assertEqual(plugin["version"], self.catalog.version)

    def test_skills_are_the_nine_category_dirs_in_order(self):
        plugin = _read_json(".cursor-plugin/plugin.json")
        expected = [f"./skills/{cat.dir}" for cat in self.catalog.categories]
        self.assertEqual(plugin["skills"], expected)

    def test_one_level_scan_finds_all_71_skills_exactly_once(self):
        plugin = _read_json(".cursor-plugin/plugin.json")
        found: list[str] = []
        for rel_dir in plugin["skills"]:
            dir_path = REPO_ROOT / rel_dir[2:] if rel_dir.startswith("./") else REPO_ROOT / rel_dir
            found.extend(_skill_names_one_level(dir_path))
        self.assertEqual(len(found), len(set(found)), "duplicate skill name found")
        self.assertEqual(sorted(found), self.all_skill_names)


class TestCodexManifest(CatalogFixture):
    def test_marketplace_entry_name_matches_plugin_manifest_name(self):
        marketplace = _read_json(".agents/plugins/marketplace.json")
        plugin = _read_json(".codex-plugin/plugin.json")
        self.assertEqual(len(marketplace["plugins"]), 1)
        entry = marketplace["plugins"][0]
        self.assertEqual(entry["name"], catalog_lib.UMBRELLA_NAME)
        self.assertEqual(plugin["name"], catalog_lib.UMBRELLA_NAME)
        self.assertEqual(entry["name"], plugin["name"])

    def test_source_resolves_to_repo_root(self):
        marketplace = _read_json(".agents/plugins/marketplace.json")
        entry = marketplace["plugins"][0]
        self.assertEqual(entry["source"], {"source": "local", "path": "./"})

    def test_plugin_version_matches_catalog(self):
        plugin = _read_json(".codex-plugin/plugin.json")
        self.assertEqual(plugin["version"], self.catalog.version)

    def test_recursive_depth_6_scan_finds_all_71_skills_exactly_once(self):
        plugin = _read_json(".codex-plugin/plugin.json")
        skills_value = plugin["skills"]
        self.assertIsInstance(skills_value, str, "codex plugin.json 'skills' must be a single path string")
        relpath = skills_value[2:] if skills_value.startswith("./") else skills_value
        root = REPO_ROOT / relpath
        found = _skill_names_recursive(root, max_depth=6)
        self.assertEqual(len(found), len(set(found)), "duplicate skill name found")
        self.assertEqual(sorted(found), self.all_skill_names)


class TestFreshness(CatalogFixture):
    def _generators(self):
        gen_files = sorted(SCRIPTS_DIR.glob("gen_*.py"))
        self.assertTrue(gen_files, "no scripts/gen_*.py found")
        return gen_files

    def test_render_is_pure_and_idempotent(self):
        for gen_path in self._generators():
            module = _load_module(gen_path)
            with self.subTest(generator=gen_path.name):
                first = module.render(self.catalog)
                second = module.render(self.catalog)
                self.assertEqual(first, second)

    def test_no_two_generators_produce_the_same_relpath(self):
        seen: dict[str, str] = {}
        for gen_path in self._generators():
            module = _load_module(gen_path)
            for relpath in module.render(self.catalog):
                with self.subTest(relpath=relpath):
                    self.assertNotIn(
                        relpath,
                        seen,
                        f"{relpath} produced by both {seen.get(relpath)} and {gen_path.name}",
                    )
                seen[relpath] = gen_path.name

    def test_generated_files_on_disk_match_renderers_byte_for_byte(self):
        for gen_path in self._generators():
            module = _load_module(gen_path)
            rendered = module.render(self.catalog)
            for relpath, text in rendered.items():
                with self.subTest(generator=gen_path.name, relpath=relpath):
                    disk_path = REPO_ROOT / relpath
                    self.assertTrue(disk_path.is_file(), f"missing {relpath} (generated by {gen_path.name})")
                    self.assertEqual(
                        text,
                        disk_path.read_text(encoding="utf-8"),
                        f"{relpath} on disk is stale relative to {gen_path.name}:render()",
                    )


if __name__ == "__main__":
    unittest.main()
