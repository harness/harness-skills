#!/usr/bin/env python3
"""Generate plugin manifests, skills.json, and the skill-table docs from the catalog.

Usage: scripts/generate_catalog.py [--check] [--list-categories]

Default mode loads the catalog (skills/categories.json + SKILL.md frontmatter),
renders every generated file -- each scripts/gen_*.py's plugin manifest(s),
skills.json, and the marked skill tables in README.md, AGENTS.md,
.cursor/rules/harness.mdc and .github/copilot-instructions.md -- and writes
only the files whose content changed. Prints "wrote <relpath>" per file
written, then a summary line. A second run writes nothing.

--check writes nothing. Prints "stale: <relpath>" for each generated file
that differs from what is on disk (or is missing), then a summary line.
Exit 1 if any file is stale, exit 0 if every file matches.

--list-categories prints one line per category: "<dir>\t<plugin>\t<n>".

Any CatalogError (bad skills/categories.json or SKILL.md) or tree error (a
gen_*.py without a usable render(), a bad or colliding output path, a doc
file missing its marker pair) is printed to stderr; exit 2.
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import catalog_lib

GENERATED_DOC_FILES = (
    "README.md",
    "AGENTS.md",
    ".cursor/rules/harness.mdc",
    ".github/copilot-instructions.md",
)
BEGIN_MARKER = "<!-- BEGIN GENERATED:skills -->"
END_MARKER = "<!-- END GENERATED:skills -->"
GENERATED_COMMENT = (
    "<!-- Generated by scripts/generate_catalog.py from skills/categories.json "
    "and SKILL.md frontmatter. Do not edit. -->"
)
REPO_SLUG = catalog_lib.REPOSITORY.removeprefix("https://github.com/")


class TreeError(Exception):
    """A structural problem with a generator or a generated-file path/marker."""


def _discover_generators() -> list[Path]:
    return sorted(Path(__file__).resolve().parent.glob("gen_*.py"))


def _load_render(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    if spec is None or spec.loader is None:
        raise TreeError(f"{path.name}: cannot load module spec")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    render = getattr(module, "render", None)
    if render is None or not callable(render):
        raise TreeError(f"{path.name}: does not define a callable render(catalog)")
    return render


def _claim(claimed: dict[str, str], relpath: object, owner: str) -> str:
    if not isinstance(relpath, str):
        raise TreeError(f"{owner}: output path {relpath!r} is not a string")
    p = Path(relpath)
    if p.is_absolute():
        raise TreeError(f"{owner}: output path {relpath!r} must be relative, not absolute")
    if ".." in p.parts:
        raise TreeError(f"{owner}: output path {relpath!r} must not contain '..'")
    if relpath in claimed:
        raise TreeError(f"{owner}: output path {relpath!r} was already produced by {claimed[relpath]}")
    claimed[relpath] = owner
    return relpath


def _run_generators(catalog: catalog_lib.Catalog, claimed: dict[str, str]) -> dict[str, str]:
    files: dict[str, str] = {}
    for gen_path in _discover_generators():
        render = _load_render(gen_path)
        result = render(catalog)
        if not isinstance(result, dict):
            raise TreeError(
                f"{gen_path.name}: render(catalog) must return a dict[str, str], "
                f"got {type(result).__name__}"
            )
        for relpath, text in result.items():
            _claim(claimed, relpath, gen_path.name)
            if not isinstance(text, str):
                raise TreeError(f"{gen_path.name}: render() value for {relpath!r} is not a string")
            files[relpath] = text
    return files


def render_skills_json(catalog: catalog_lib.Catalog) -> str:
    plugins = [
        {
            "name": cat.plugin,
            "dir": f"skills/{cat.dir}",
            "title": cat.title,
            "description": cat.description,
            "category": cat.category,
            "skills": sorted(skill.name for skill in cat.skills),
        }
        for cat in catalog.categories
    ]
    skills = [
        {
            "name": skill.name,
            "plugin": catalog.category(skill.category).plugin,
            "path": skill.path,
            "summary": skill.summary,
            "version": skill.version,
            "mcp_server": skill.mcp_server,
            "compatibility": skill.compatibility,
        }
        for skill in catalog.skills
    ]
    data = {
        "name": catalog_lib.MARKETPLACE_NAME,
        "version": catalog.version,
        "repository": catalog_lib.REPOSITORY,
        "plugins": plugins,
        "skills": skills,
    }
    return catalog_lib.render_json(data)


def _skill_table_body_lines(catalog: catalog_lib.Catalog, readme_style: bool) -> list[str]:
    lines: list[str] = [GENERATED_COMMENT, ""]
    for cat in catalog.categories:
        lines.append(f"### {cat.title}")
        lines.append("")
        if readme_style:
            n_label = catalog_lib.count_label(len(cat.skills))
            lines.append(f"Plugin `{cat.plugin}` ({n_label}), folder `skills/{cat.dir}/`.")
            lines.append(
                f"Install in Claude Code: `/plugin install {cat.plugin} --marketplace {REPO_SLUG}`."
            )
            lines.append("")
            lines.append("| Skill | Invoke in Claude Code | Description |")
            lines.append("|-------|------------------------|-------------|")
            for skill in cat.skills:
                lines.append(
                    f"| [{skill.name}](skills/{cat.dir}/{skill.name}/SKILL.md) | "
                    f"`/{cat.plugin}:{skill.name}` | {skill.summary} |"
                )
        else:
            lines.append(f"Plugin `{cat.plugin}`, folder `skills/{cat.dir}/`.")
            lines.append("")
            lines.append("| Skill | Description |")
            lines.append("|-------|-------------|")
            for skill in cat.skills:
                lines.append(f"| `/{skill.name}` | {skill.summary} |")
        lines.append("")
    return lines


def _replace_marker_block(relpath: str, text: str, body_lines: list[str]) -> str:
    lines = text.split("\n")
    begin_idxs = [i for i, line in enumerate(lines) if line == BEGIN_MARKER]
    end_idxs = [i for i, line in enumerate(lines) if line == END_MARKER]
    if len(begin_idxs) != 1 or len(end_idxs) != 1:
        raise TreeError(
            f"{relpath}: expected exactly one BEGIN/END GENERATED:skills marker pair, "
            f"found {len(begin_idxs)} BEGIN and {len(end_idxs)} END"
        )
    begin_i, end_i = begin_idxs[0], end_idxs[0]
    if end_i <= begin_i:
        raise TreeError(f"{relpath}: END marker appears before BEGIN marker")
    new_lines = lines[: begin_i + 1] + body_lines + lines[end_i:]
    return "\n".join(new_lines)


def render_doc_file(root: Path, relpath: str, catalog: catalog_lib.Catalog) -> str:
    path = root / relpath
    if not path.is_file():
        raise TreeError(f"{relpath}: file not found")
    text = path.read_text(encoding="utf-8")
    body_lines = _skill_table_body_lines(catalog, readme_style=(relpath == "README.md"))
    return _replace_marker_block(relpath, text, body_lines)


def render_all(catalog: catalog_lib.Catalog) -> dict[str, str]:
    """Render every generated file. Returns {relpath: full file text}."""
    claimed: dict[str, str] = {}
    files = _run_generators(catalog, claimed)

    _claim(claimed, "skills.json", "generate_catalog.py")
    files["skills.json"] = render_skills_json(catalog)

    for relpath in GENERATED_DOC_FILES:
        _claim(claimed, relpath, "generate_catalog.py")
        files[relpath] = render_doc_file(catalog.root, relpath, catalog)

    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="scripts/generate_catalog.py", description=__doc__.splitlines()[0]
    )
    parser.add_argument("--check", action="store_true", help="report staleness, write nothing")
    parser.add_argument(
        "--list-categories", action="store_true", help="print '<dir>\\t<plugin>\\t<n>' per category"
    )
    args = parser.parse_args(argv)

    try:
        catalog = catalog_lib.load_catalog()
    except catalog_lib.CatalogError as exc:
        print(str(exc), file=sys.stderr)
        return 2

    if args.list_categories:
        for cat in catalog.categories:
            print(f"{cat.dir}\t{cat.plugin}\t{len(cat.skills)}")
        return 0

    try:
        files = render_all(catalog)
    except (catalog_lib.CatalogError, TreeError) as exc:
        print(str(exc), file=sys.stderr)
        return 2

    root = catalog.root

    if args.check:
        stale = []
        for relpath in sorted(files):
            path = root / relpath
            if not path.is_file() or path.read_text(encoding="utf-8") != files[relpath]:
                stale.append(relpath)
        for relpath in stale:
            print(f"stale: {relpath}")
        print(f"{len(stale)} of {len(files)} generated files stale")
        return 1 if stale else 0

    written = []
    for relpath in sorted(files):
        path = root / relpath
        text = files[relpath]
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(relpath)
        print(f"wrote {relpath}")
    print(f"wrote {len(written)} of {len(files)} generated files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
