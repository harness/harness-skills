# Every plugin manifest in this repo (the 9 Claude Code plugins and the
# Cursor/Codex umbrella plugins) declares source: "." / path: "./" -- the
# repo root. Any of these paths at the repo root would therefore be
# auto-loaded by every one of those plugins and ship to every plugin user,
# not just agents working from a clone. Reproduced with `claude plugin
# details` showing an injected MCP server and hook when a root .mcp.json
# and hooks/hooks.json were added.
ROOT_FORBIDDEN_NAMES = (
    ".mcp.json",
    "mcp.json",
    ".lsp.json",
    ".app.json",
    "settings.json",
    "hooks",
    "commands",
    "agents",
    "bin",
    "rules",
    "output-styles",
    "monitors",
)


class TestRootPluginSurface(unittest.TestCase):
    def test_no_root_level_plugin_components_that_would_ship_to_every_plugin(self):
        for name in ROOT_FORBIDDEN_NAMES:
            path = REPO_ROOT / name
            with self.subTest(name=name):
                self.assertFalse(
                    path.exists(),
                    f"{name} must not exist at the repo root: every plugin here is rooted "
                    f'at the repo (source: "." / path: "./"), so this file or directory would '
                    "be auto-loaded by all of them and ship to every plugin user, not just "
                    "this repo's own agents.",
                )

    def test_claude_plugin_dir_contains_only_marketplace_json(self):
        claude_plugin_dir = REPO_ROOT / ".claude-plugin"
        self.assertTrue(claude_plugin_dir.is_dir())
        entries = sorted(p.name for p in claude_plugin_dir.iterdir())
        self.assertEqual(
            entries,
            ["marketplace.json"],
            ".claude-plugin/ must contain only marketplace.json: any other file (e.g. "
            "plugin.json, a hooks config) would be picked up by every plugin sourced "
            "from the repo root and ship to every plugin user.",
        )


class TestFreshness(CatalogFixture):
    def _generators(self):
        gen_files = sorted(SCRIPTS_DIR.glob("gen_*.py"))
        self.assertTrue(gen_files, "no scripts/gen_*.py found")
        return gen_files

    def test_render_is_pure_and_idempotent(self):
        for gen_path in self._generators():
            module = _load_module(gen_path)
            with self.subTest(generator=gen_path.name):
                first = module.render(self.catalog)
                second = module.render(self.catalog)
                self.assertEqual(first, second)

    def test_no_two_generators_produce_the_same_relpath(self):
        seen: dict[str, str] = {}
        for gen_path in self._generators():
            module = _load_module(gen_path)
            for relpath in module.render(self.catalog):
                with self.subTest(relpath=relpath):
                    self.assertNotIn(
                        relpath,
                        seen,
                        f"{relpath} produced by both {seen.get(relpath)} and {gen_path.name}",
                    )
                seen[relpath] = gen_path.name

    def test_generated_files_on_disk_match_renderers_byte_for_byte(self):
        for gen_path in self._generators():
            module = _load_module(gen_path)
            rendered = module.render(self.catalog)
            for relpath, text in rendered.items():
                with self.subTest(generator=gen_path.name, relpath=relpath):
                    disk_path = REPO_ROOT / relpath
                    self.assertTrue(disk_path.is_file(), f"missing {relpath} (generated by {gen_path.name})")
                    self.assertEqual(
                        text,
                        disk_path.read_text(encoding="utf-8"),
                        f"{relpath} on disk is stale relative to {gen_path.name}:render()",
                    )


